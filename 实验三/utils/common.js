//分类列表
const categories = ['全部', '海大要闻', '综合新闻', '媒体海大', '学术海大'];

//获取新闻列表（支持分类筛选，按时间倒序）
function getNewsList(category) {
  let list = [];
  for (var i = 0; i < news.length; i++) {
    if (!category || category === '全部' || news[i].category === category) {
      let obj = {};
      obj.id = news[i].id;
      obj.poster = news[i].poster;
      obj.add_date = news[i].add_date;
      obj.title = news[i].title;
      obj.category = news[i].category;
      list.push(obj);
    }
  }
  // 按日期倒序排序（最新的在前）
  list.sort(function(a, b) {
    return b.add_date.localeCompare(a.add_date);
  });
  return list;
}

//获取轮播图新闻（按时间排序后取最新的 3 条）
function getSwiperNews() {
  let list = [];
  // 按日期倒序排序（最新的在前）
  let sorted = news.slice().sort(function(a, b) {
    return b.add_date.localeCompare(a.add_date);
  });
  let count = Math.min(3, sorted.length);
  for (var i = 0; i < count; i++) {
    list.push({
      id: sorted[i].id,
      src: sorted[i].poster,
      title: sorted[i].title
    });
  }
  return list;
}

//获取新闻内容
function getNewsDetail(newsID) {
  let msg = {
    code: '404',
    news: {}
  };
  for (var i = 0; i < news.length; i++) {
    if (newsID == news[i].id) {
      msg.code = '200';
      msg.news = news[i];
      break;
    }
  }
  return msg;
}

//获取分类列表
function getCategories() {
  return categories;
}

// 对外暴露接口
module.exports = {
  getNewsList: getNewsList,
  getSwiperNews: getSwiperNews,
  getNewsDetail: getNewsDetail,
  getCategories: getCategories
}
